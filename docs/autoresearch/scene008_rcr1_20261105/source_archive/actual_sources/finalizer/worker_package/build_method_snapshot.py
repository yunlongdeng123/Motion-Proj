def extract(path, methods, functions):
    text = path.read_text(encoding='utf-8')
    tree = ast.parse(text)
    selected = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in functions:
            selected[node.name] = ast.get_source_segment(text, node)
        if isinstance(node, ast.ClassDef) and node.name == 'Experiment':
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name in methods:
                    selected[item.name] = ast.get_source_segment(text, item)
    assert set(selected) == set(methods) | set(functions)
    return selected


